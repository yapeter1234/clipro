"""Discover the VOD associated with the current live Twitch broadcast.

Twitch's Create Clip From VOD endpoint supports a VOD that is still being
generated by a live broadcast. The API may not expose that in-progress VOD in
every channel/configuration. This module matches stream_id exactly and returns
None when the active VOD is not listed; callers must then use an authorized
manual clip/file fallback rather than guessing a prior VOD.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Any

from services.api.app.providers.twitch import TwitchHelixClient


@dataclass(frozen=True, slots=True)
class ActiveVod:
    vod_id: str
    stream_id: str
    broadcaster_id: str
    created_at: str | None
    title: str
    duration: str | None
    url: str | None


async def find_vod_for_active_stream(
    client: TwitchHelixClient,
    *,
    broadcaster_id: str,
    stream_id: str,
    first: int = 100,
) -> ActiveVod | None:
    """Find an archive VOD whose stream_id exactly matches the live stream."""
    if not broadcaster_id.strip() or not stream_id.strip():
        raise ValueError("broadcaster_id and stream_id are required")
    page = await client.list_vods(
        broadcaster_id,
        first=first,
        video_type="archive",
    )
    for item in page.get("data") or []:
        if (
            str(item.get("stream_id") or "") == stream_id
            and str(item.get("user_id") or "") == broadcaster_id
            and str(item.get("type") or "") == "archive"
        ):
            vod_id = str(item.get("id") or "")
            if not vod_id:
                continue
            return ActiveVod(
                vod_id=vod_id,
                stream_id=stream_id,
                broadcaster_id=broadcaster_id,
                created_at=item.get("created_at"),
                title=str(item.get("title") or ""),
                duration=item.get("duration"),
                url=item.get("url"),
            )
    return None


async def get_diego_live_vod(
    client: TwitchHelixClient,
) -> tuple[dict[str, Any], ActiveVod] | None:
    """Return (live stream, matching active VOD) for Diego only.

    Rejects offline streams, wrong creators, wrong categories, or situations
    where Twitch hasn't exposed the VOD ID yet.
    """
    from services.worker.app.campaign_gate import evaluate_diego_gta6_stream

    creator = await client.get_user("diegoloveless")
    if not creator or not creator.get("id"):
        return None
    stream = await client.get_stream(str(creator["id"]))
    result = evaluate_diego_gta6_stream(stream)
    if not result.eligible:
        return None
    active_vod = await find_vod_for_active_stream(
        client,
        broadcaster_id=str(creator["id"]),
        stream_id=str(stream["id"]),
    )
    if active_vod is None:
        return None
    return stream, active_vod
